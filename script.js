function resize() {
  const zoomLevel = window.devicePixelRatio;
  const targetZoom = 1 / zoomLevel;
  document.body.style.zoom = `${targetZoom}`;
}

function change_image(id) {
  current_image_index = id;
  const current_img = document.getElementById("selected-img");
  const current_header = document.getElementById("selected-header");
  const current_text = document.getElementById("selected-text");
  current_img.src = `images/${current_image_index}.jpg`;
  current_header.innerHTML = texts[current_image_index][0];
  current_text.innerHTML = texts[current_image_index][1];
}

function load_gallry() {
  const gallery_grid = document.getElementById("gallery").lastElementChild;
  const overflow = document.getElementById("overflow");
  overflow.onclick = (e) => {
    list.style.display = "none";
    overflow.style.display = "none";
  };
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
      list.style.display = "none";
      overflow.style.display = "none";
    }
  });
  const list = document.getElementById("list");
  const current_img = document.getElementById("selected-img");

  for (let i = 0; i < 9; i++) {
    let el = document.createElement("img");
    el.src = `images/${i}.jpg`;
    el.className = "grid-image";
    el.onclick = (e) => {
      list.style.display = "flex";
      overflow.style.display = "flex";
      change_image(i);
    };

    gallery_grid.appendChild(el);
  }
}

addEventListener("DOMContentLoaded", (event) => {
  resize();
  load_gallry();
});

window.visualViewport.addEventListener("resize", () => {
  resize();
});
